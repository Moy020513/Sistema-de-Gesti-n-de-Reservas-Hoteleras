CREATE TABLE ADMIN.HUESPEDES (
    ID_HUESPED NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50 ) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50 ) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50 ) NOT NULL,
    EMAIL VARCHAR2(100 ) NOT NULL,
    TELEFONO VARCHAR2(10) NOT NULL,
    DOCUMENTO VARCHAR2(20) NOT NULL,
    NACIONALIDAD VARCHAR2(20) NOT NULL,
    ESTADO_REGISTRO VARCHAR2(10) NOT NULL,
    CONSTRAINT HUESPED_PK PRIMARY KEY (ID_HUESPED),
    CONSTRAINT CHK_ESTADO_REGISTRO_HUESPED CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
    
);

CREATE TABLE ADMIN.HABITACIONES (
    ID_HABITACION NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    NUMERO NUMBER(3) NOT NULL,
    TIPO VARCHAR2(50 ) NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL,
    CAPACIDAD NUMBER(2) NOT NULL,
    ESTADO_INICIAL VARCHAR2(20) NOT NULL,
    ESTADO_REGISTRO VARCHAR2(10) NOT NULL,
    CONSTRAINT HABITACION_PK PRIMARY KEY (ID_HABITACION),
    CONSTRAINT CHK_HABITACIONES_NUMERO CHECK (NUMERO > 0),
    CONSTRAINT CHK_HABITACIONES_CAPACIDAD CHECK (CAPACIDAD > 0),
    CONSTRAINT CHK_HABITACIONES_PRECIO CHECK (PRECIO > 0),
    CONSTRAINT CHK_ESTADO_INICIAL_HABITACION CHECK (ESTADO_INICIAL IN ('DISPONIBLE', 'OCUPADA', 'LIMPIEZA','MANTENIMIENTO')),
    CONSTRAINT CHK_ESTADO_REGISTRO_HABITACION CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
    
);

CREATE TABLE ADMIN.RESERVAS (
    ID_RESERVA NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    ID_HUESPED NUMBER(10) NOT NULL,
    ID_HABITACION NUMBER(10) NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,
    ESTADO_INICIO VARCHAR2(20) NOT NULL,
    ESTADO_REGISTRO VARCHAR2(10) NOT NULL,
    CONSTRAINT RESERVA_PK PRIMARY KEY (ID_RESERVA),
    CONSTRAINT CHK_ESTADO_INICIAL_RESERVA CHECK (ESTADO_INICIO IN ('CONFIRMADA', 'EN_CURSO', 'FINALIZADA','CANCELADA')),
    CONSTRAINT CHK_ESTADO_REGISTRO_RESERVA CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

