CREATE TABLE ADMIN.USUARIOS (
    ID_USUARIO NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    USERNAME VARCHAR2(20) NOT NULL,
    PASSWORD_USER VARCHAR2(100) NOT NULL,
    ROL NUMBER(10) NOT NULL,
    ESTADO_REGISTRO VARCHAR2(10) NOT NULL,
    
    CONSTRAINT USUARIO_PK PRIMARY KEY (ID_USUARIO),
    CONSTRAINT CHK_ROL CHECK (ROL IN ('ADMIN', 'USER')),
    CONSTRAINT CHK_ESTADO_REGISTRO_USUARIO CHECK (ESTADO_REGISTRO IN ('ACTIVO', 'ELIMINADO'))
);

